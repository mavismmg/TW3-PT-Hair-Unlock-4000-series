inline constexpr std::array<uint32_t,2> kRendererDeviceReturnRvas{0x1ec4889u,0x1ec48c2u};
inline const void* RendererDeviceCaller(uintptr_t image,std::span<void* const> frames) noexcept {
    if(!image)return nullptr;
    for(const void* frame:frames)for(const auto rva:kRendererDeviceReturnRvas)
        if(reinterpret_cast<uintptr_t>(frame)==image+rva)return frame;
    return nullptr;
}
